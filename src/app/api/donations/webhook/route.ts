import crypto from "crypto";
import { NextRequest, NextResponse } from "next/server";
import prisma from "@/lib/prisma";
import { invalidate } from "@/lib/cache";
import { DonationStatus } from "@/generated/prisma/enums";
import { badRequest, internalError, notFound, ok } from "@/lib/api-response";

/**
 * @swagger
 * /api/donations/webhook:
 *   post:
 *     summary: Midtrans Webhook Callback
 *     description: Secret endpoint called automatically by Midtrans backend upon payment state changes (capture, settlement, expire, cancel, or deny). It updates the status of the donation and triggers funding updates on the relative project.
 *     tags:
 *       - Donations
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             properties:
 *               order_id:
 *                 type: string
 *                 description: ID order generated by Livon's backend.
 *               transaction_status:
 *                 type: string
 *                 description: Status of the transaction from Midtrans (e.g. 'capture', 'settlement', 'cancel', 'deny', 'expire').
 *               transaction_id:
 *                 type: string
 *               payment_type:
 *                 type: string
 *     responses:
 *       200:
 *         description: Webhook processed successfully or acknowledged.
 *       404:
 *         description: Order Not Found. The provided order_id does not exist in the database.
 *       500:
 *         description: Webhook processing error. An internal server error occurred while updating states.
 */
export async function POST(req: NextRequest) {
  try {
    const serverKey = process.env.MIDTRANS_SERVER_KEY;
    if (!serverKey) {
      console.error("MIDTRANS_SERVER_KEY is not configured");
      return internalError("Webhook configuration error");
    }

    const body = await req.json();

    const {
      order_id,
      status_code,
      gross_amount,
      signature_key,
      transaction_status,
      transaction_id,
      payment_type,
    } = body;

    if (
      typeof order_id !== "string" ||
      typeof status_code !== "string" ||
      typeof gross_amount !== "string" ||
      typeof signature_key !== "string" ||
      typeof transaction_status !== "string"
    ) {
      return badRequest("Invalid webhook payload");
    }

    const expectedSignature = crypto
      .createHash("sha512")
      .update(`${order_id}${status_code}${gross_amount}${serverKey}`)
      .digest("hex");

    const providedBuf = Buffer.from(signature_key, "utf8");
    const expectedBuf = Buffer.from(expectedSignature, "utf8");
    if (
      providedBuf.length !== expectedBuf.length ||
      !crypto.timingSafeEqual(providedBuf, expectedBuf)
    ) {
      return NextResponse.json(
        { success: false, message: "Invalid webhook signature" },
        { status: 403 },
      );
    }

    const donation = await prisma.donation.findUnique({
      where: { orderId: order_id },
      include: { project: true },
    });

    if (!donation?.orderId) {
      return notFound("Order Not Found");
    }

    const reportedAmount = Number(gross_amount);
    if (
      !Number.isFinite(reportedAmount) ||
      reportedAmount !== Number(donation.amount)
    ) {
      return badRequest("Webhook amount mismatch");
    }

    if (donation.status === DonationStatus.SUCCESS) {
      return ok("Donation already processed");
    }

    if (
      transaction_status === "capture" ||
      transaction_status === "settlement"
    ) {
      const processed = await prisma.$transaction(async (tx) => {
        const updated = await tx.donation.updateMany({
          where: {
            orderId: order_id,
            status: { not: DonationStatus.SUCCESS },
          },
          data: {
            status: DonationStatus.SUCCESS,
            gatewayTransactionId: transaction_id,
            paymentMethod: payment_type,
            paidAt: new Date(),
          },
        });

        if (updated.count === 0) {
          return false;
        }

        await tx.project.update({
          where: { id: donation.projectId },
          data: {
            currentFunding: { increment: donation.amount },
          },
        });

        return true;
      });

      if (!processed) {
        return ok("Donation already processed");
      }

      await prisma.notification.create({
        data: {
          userId: donation.userId,
          projectId: donation.projectId,
          referenceId: donation.id,
          title: "Donation Successful",
          type: "DONATION_SUCCESS",
          message: `Your donation of Rp ${donation.amount} was successful. Thank you!`,
        },
      });

      if (donation.project.agencyId) {
        await prisma.notification.create({
          data: {
            userId: donation.project.agencyId,
            projectId: donation.projectId,
            referenceId: donation.id,
            title: "New Donation Received",
            type: "NEW_DONATION",
            message: `Your project received a new donation of Rp ${donation.amount}.`,
          },
        });
      }
    } else if (
      transaction_status === "cancel" ||
      transaction_status === "deny" ||
      transaction_status === "expire"
    ) {
      const updated = await prisma.donation.updateMany({
        where: {
          orderId: order_id,
          status: { not: DonationStatus.SUCCESS },
        },
        data: {
          status: DonationStatus.FAILED,
          gatewayTransactionId: transaction_id,
          paymentMethod: payment_type,
        },
      });

      if (updated.count === 0) {
        return ok("Donation already processed");
      }

      await prisma.notification.create({
        data: {
          userId: donation.userId,
          projectId: donation.projectId,
          referenceId: donation.id,
          title: "Donation Failed",
          type: "DONATION_FAILED",
          message: `Your donation of Rp ${donation.amount} failed to process. Please try again.`,
        },
      });
    }

    await invalidate("projects", "dashboard");
    return ok("Webhook acknowledged");
  } catch (error) {
    console.error(error);
    return internalError("Webhook processing error");
  }
}
